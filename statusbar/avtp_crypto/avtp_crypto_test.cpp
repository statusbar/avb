    auto wrapped = wrap_aes256_key(transport_key, controller_nonce, target_nonce, key_id, stream_key);

    // Correct nonces: should succeed
    auto ok = unwrap_aes256_key(transport_key, controller_nonce, target_nonce, key_id, wrapped);
