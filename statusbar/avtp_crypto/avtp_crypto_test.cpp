TEST(avtp_crypto, unwrap_tampered_key)
{
    // clang-format off
    Aes256SivKey transport_key = {{{
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f,
        0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x28,0x29,0x2a,0x2b,0x2c,0x2d,0x2e,0x2f,
        0x30,0x31,0x32,0x33,0x34,0x35,0x36,0x37,0x38,0x39,0x3a,0x3b,0x3c,0x3d,0x3e,0x3f,
    }}};
    Aes256Key stream_key = {{
        0xaa,0xbb,0xcc,0xdd,0xee,0xff,0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,
        0xaa,0xbb,0xcc,0xdd,0xee,0xff,0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,
    }};
    // clang-format on

    Nonce controller_nonce{};
    controller_nonce.data = {0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7};
    Nonce target_nonce{};
    target_nonce.data = {0xD0, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7};
    KeyId key_id{};
    key_id.data = {0x10, 0x20, 0x30, 0x40, 0x50, 0x60, 0x70, 0x80};

    auto wrapped = wrap_aes256_key(transport_key, controller_nonce, target_nonce, key_id, stream_key);

    // Tamper with the ciphertext
    auto tampered_ct = wrapped;
    tampered_ct.ciphertext[0] ^= 0x01;
    auto result1 = unwrap_aes256_key(transport_key, controller_nonce, target_nonce, key_id, tampered_ct);
    EXPECT_TRUE(!result1.has_value());

    // Tamper with the SIV tag
    auto tampered_tag = wrapped;
    tampered_tag.siv_tag[0] ^= 0x01;
    auto result2 = unwrap_aes256_key(transport_key, controller_nonce, target_nonce, key_id, tampered_tag);
    EXPECT_TRUE(!result2.has_value());

    // Tamper with the controller_nonce (AAD)
    Nonce bad_controller_nonce{};
    bad_controller_nonce.data = {0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xFF};
    auto result3 = unwrap_aes256_key(transport_key, bad_controller_nonce, target_nonce, key_id, wrapped);
    EXPECT_TRUE(!result3.has_value());

    // Tamper with the target_nonce (AAD)
    Nonce bad_target_nonce{};
    bad_target_nonce.data = {0xD0, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xFF};
    auto result4 = unwrap_aes256_key(transport_key, controller_nonce, bad_target_nonce, key_id, wrapped);
    EXPECT_TRUE(!result4.has_value());
}

