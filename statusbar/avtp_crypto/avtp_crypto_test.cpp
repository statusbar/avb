// ===========================================================================
// Ed25519 + X25519 full protocol roundtrip
// ===========================================================================

TEST(avtp_crypto, ed25519_full_protocol_roundtrip)
{
    // clang-format off
    std::array<uint8_t, 32> controller_identity_seed = {
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x10,
        0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f,0x20,
    };
    std::array<uint8_t, 32> endpoint_identity_seed = {
        0x21,0x22,0x23,0x24,0x25,0x26,0x27,0x28,0x29,0x2a,0x2b,0x2c,0x2d,0x2e,0x2f,0x30,
        0x31,0x32,0x33,0x34,0x35,0x36,0x37,0x38,0x39,0x3a,0x3b,0x3c,0x3d,0x3e,0x3f,0x40,
    };
    std::array<uint8_t, 32> controller_ephemeral_seed = {
        0x41,0x42,0x43,0x44,0x45,0x46,0x47,0x48,0x49,0x4a,0x4b,0x4c,0x4d,0x4e,0x4f,0x50,
        0x51,0x52,0x53,0x54,0x55,0x56,0x57,0x58,0x59,0x5a,0x5b,0x5c,0x5d,0x5e,0x5f,0x60,
    };
    std::array<uint8_t, 32> endpoint_ephemeral_seed = {
        0x61,0x62,0x63,0x64,0x65,0x66,0x67,0x68,0x69,0x6a,0x6b,0x6c,0x6d,0x6e,0x6f,0x70,
        0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0x79,0x7a,0x7b,0x7c,0x7d,0x7e,0x7f,0x80,
    };
    // clang-format on

    auto controller_id = ed25519_keypair_from_seed(controller_identity_seed);
    auto endpoint_id = ed25519_keypair_from_seed(endpoint_identity_seed);
    auto controller_id_pk = ed25519_public_key(controller_id);
    auto endpoint_id_pk = ed25519_public_key(endpoint_id);

    auto controller_eph = x25519_keypair_from_seed(controller_ephemeral_seed);
    auto endpoint_eph = x25519_keypair_from_seed(endpoint_ephemeral_seed);

    // Controller builds offer, endpoint verifies
    auto offer = build_ed25519_key_exchange(key_exchange_offer, controller_id, controller_eph.public_key);
    EXPECT_TRUE(offer.message_type == key_exchange_offer);
    auto offer_result = verify_ed25519_key_exchange(offer, controller_id_pk);
    EXPECT_TRUE(offer_result.has_value());
    EXPECT_TRUE(span_compare(offer_result->data, controller_eph.public_key.data));

    // Endpoint builds accept, controller verifies
    auto accept = build_ed25519_key_exchange(key_exchange_accept, endpoint_id, endpoint_eph.public_key);
    EXPECT_TRUE(accept.message_type == key_exchange_accept);
    auto accept_result = verify_ed25519_key_exchange(accept, endpoint_id_pk);
    EXPECT_TRUE(accept_result.has_value());
    EXPECT_TRUE(span_compare(accept_result->data, endpoint_eph.public_key.data));

    // Both sides compute shared secret
    auto controller_shared = x25519(controller_eph, endpoint_eph.public_key);
    auto endpoint_shared = x25519(endpoint_eph, controller_eph.public_key);
    EXPECT_TRUE(span_compare(controller_shared, endpoint_shared));
    EXPECT_TRUE(x25519_shared_secret_is_valid(controller_shared));

    // Both sides derive transport key
    auto controller_transport = derive_ed25519_transport_key(controller_shared, controller_id_pk, endpoint_id_pk);
    auto endpoint_transport = derive_ed25519_transport_key(endpoint_shared, controller_id_pk, endpoint_id_pk);
    EXPECT_TRUE(span_compare(controller_transport.data, endpoint_transport.data));

    // Controller wraps stream key, endpoint unwraps
    // clang-format off
    Aes256Key stream_key = {{
        0xa0,0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0xa7,0xa8,0xa9,0xaa,0xab,0xac,0xad,0xae,0xaf,
        0xb0,0xb1,0xb2,0xb3,0xb4,0xb5,0xb6,0xb7,0xb8,0xb9,0xba,0xbb,0xbc,0xbd,0xbe,0xbf,
    }};
    // clang-format on
    Nonce controller_nonce{};
    controller_nonce.data = {0xC0, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7};
    Nonce target_nonce{};
    target_nonce.data = {0xD0, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7};
    KeyId key_id{};
    key_id.data = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07};

    auto wrapped = wrap_aes256_key(controller_transport, controller_nonce, target_nonce, key_id, stream_key);
    EXPECT_TRUE(!span_compare(wrapped.ciphertext, stream_key.data));

    auto unwrapped = unwrap_aes256_key(endpoint_transport, controller_nonce, target_nonce, key_id, wrapped);
    EXPECT_TRUE(unwrapped.has_value());
    EXPECT_TRUE(span_compare(unwrapped->data, stream_key.data));
}

